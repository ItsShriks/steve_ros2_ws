#!/usr/bin/env python3
"""
Generate config/steve.srdf from the expanded robot URDF (MMO-700 + UR5e + Robotiq 2F-85).

    xacro $(ros2 pkg prefix steve_simulation)/share/steve_simulation/robots/mmo_700/mmo_700.urdf.xacro \
        arm_type:=ur5e arm_tool:=robotiq_2f_85 include_pan_tilt:=true include_wrist_camera:=true > /tmp/steve.urdf
    python3 tools/generate_srdf.py /tmp/steve.urdf config/steve.srdf

Collision matrix rules (instead of the Setup Assistant's sampling):
  * links joined by fixed joints form one rigid group            -> never checked against each other
  * rigid groups joined by one movable joint (adjacent)          -> not checked
  * the whole robot body (everything that is not arm/gripper)    -> not checked internally
  * UR base / shoulder vs body (the arm sits on the cabinet)     -> not checked
  * wrist_3 + flange + camera + adapter + gripper (one cluster)  -> not checked internally
  * wrist_1 vs wrist_3 (UR "never" pair, ur_moveit_config)       -> not checked
Everything else (e.g. forearm/wrist/gripper vs base, cabinet, pan-tilt, lidars) IS checked.
Refine with the MoveIt Setup Assistant if MoveIt reports a false start-state collision.
"""
import sys
import xml.etree.ElementTree as ET
from itertools import combinations

P = "ur5e"
ARM_JOINTS = [f"{P}{j}" for j in ("shoulder_pan_joint", "shoulder_lift_joint", "elbow_joint",
                                   "wrist_1_joint", "wrist_2_joint", "wrist_3_joint")]
GRIPPER_JOINT = "robotiq_85_left_knuckle_joint"
NAMED_ARM = {  # shoulder_pan, shoulder_lift, elbow, wrist_1, wrist_2, wrist_3
    "home":        [0.0, -1.5708, 1.5708, -1.5708, -1.5708, 0.0],   # compact drive pose
    "ready":       [0.0, -1.2, 1.2, -1.6, -1.57, 0.0],              # raised, gripper down
    "table_reach": [0.0, -1.0, 1.5, -2.05, -1.57, 0.0],             # reach forward, gripper down
    "forward":     [0.0, -1.558, 2.075, -0.516, 1.571, 0.0],        # gripper pointing forward
    "parked":      [-0.0001, -1.5708, 2.6180, -1.1344, 0.0001, 0.1571],  # folded (tools/save_named_pose.py, 2026-10-14)
    "explore":     [-1.5708, -1.5708, 1.5708, -2.0071, -1.5708, 0.0],   # home, camera tilted 25 deg at the table
}
NAMED_GRIPPER = {"open": 0.0, "closed": 0.7929}


def main(urdf_path, srdf_path):
    r = ET.parse(urdf_path).getroot()
    links = [l.get("name") for l in r.findall("link")]
    has_geom = {l.get("name") for l in r.findall("link") if l.find("collision") is not None}
    joints = [(j.get("name"), j.get("type"), j.find("parent").get("link"), j.find("child").get("link"))
              for j in r.findall("joint")]
    children = {}
    for n, t, p, c in joints:
        children.setdefault(p, []).append(c)

    def subtree(root):
        out, stack = set(), [root]
        while stack:
            x = stack.pop()
            out.add(x)
            stack += children.get(x, [])
        return out

    child_of = {n: c for n, t, p, c in joints}
    arm = subtree(child_of[ARM_JOINTS[0]])           # shoulder and everything after it
    body = set(links) - arm
    wrist3 = subtree(child_of[ARM_JOINTS[-1]])        # wrist_3 + flange + tool0 + camera + gripper

    # rigid groups (union-find over fixed joints)
    parent = {l: l for l in links}
    find = lambda x: x if parent[x] == x else find(parent[x])
    for n, t, p, c in joints:
        if t == "fixed":
            parent[find(c)] = find(p)
    group = {l: find(l) for l in links}

    disabled = {}

    def dis(a, b, reason):
        if a != b and a in has_geom and b in has_geom:
            disabled.setdefault(tuple(sorted((a, b))), reason)

    for a, b in combinations(links, 2):
        if group[a] == group[b]:
            dis(a, b, "Adjacent")
    for n, t, p, c in joints:
        if t != "fixed":
            for a in links:
                for b in links:
                    if group[a] == group[p] and group[b] == group[c]:
                        dis(a, b, "Adjacent")
    for a, b in combinations(sorted(body), 2):
        dis(a, b, "Never")
    for a in (f"{P}base_link_inertia", f"{P}shoulder_link"):
        for b in body:
            dis(a, b, "Never")
    for a, b in combinations(sorted(wrist3), 2):
        dis(a, b, "Never")
    for b in wrist3:
        dis(f"{P}wrist_1_link", b, "Never")

    missing = [j for j in ARM_JOINTS + [GRIPPER_JOINT] if j not in {n for n, *_ in joints}]
    if missing:
        sys.exit(f"URDF is missing joints {missing} — expand with arm_tool:=robotiq_2f_85")
    root = [l for l in links if l not in {c for *_, c in joints}][0]

    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           f'<!-- Generated by tools/generate_srdf.py from the MMO-700 + UR5e + Robotiq 2F-85 URDF. -->',
           '<robot name="mmo_700">',
           '    <!-- Arm: UR5e base to the gripper tool centre point -->',
           '    <group name="ur_manipulator">',
           f'        <chain base_link="{P}base_link" tip_link="gripper_tcp"/>',
           '    </group>',
           '    <group name="gripper">',
           f'        <joint name="{GRIPPER_JOINT}"/>',
           '    </group>', '']
    for name, q in NAMED_ARM.items():
        out.append(f'    <group_state name="{name}" group="ur_manipulator">')
        out += [f'        <joint name="{j}" value="{v}"/>' for j, v in zip(ARM_JOINTS, q)]
        out.append('    </group_state>')
    for name, v in NAMED_GRIPPER.items():
        out.append(f'    <group_state name="{name}" group="gripper">')
        out.append(f'        <joint name="{GRIPPER_JOINT}" value="{v}"/>')
        out.append('    </group_state>')
    out += ['',
            '    <end_effector name="robotiq_2f_85" parent_link="robotiq_85_base_link" group="gripper" '
            'parent_group="ur_manipulator"/>', '',
            f'    <!-- The mobile base is not planned by MoveIt: root link {root} is the planning frame -->', '']
    out += [f'    <disable_collisions link1="{a}" link2="{b}" reason="{why}"/>'
            for (a, b), why in sorted(disabled.items())]
    out.append('</robot>')
    open(srdf_path, "w").write("\n".join(out) + "\n")
    checked = len(list(combinations(sorted(has_geom), 2))) - len(disabled)
    print(f"root={root}  links with collision={len(has_geom)}  disabled pairs={len(disabled)}  "
          f"checked pairs={checked}  -> {srdf_path}")


if __name__ == "__main__":
    main(*sys.argv[1:3])
