# Steve ROS 2 network selection. Installed to ~/.ros/steve_dds.sh by scripts/steve_laptop_setup.sh and
# sourced from ~/.bashrc (after the workspace's setup.bash).
#
#   cable to the robot (this PC has a 192.168.60.x address from the robot's DHCP)
#       -> Ethernet: ~/.ros/fastdds_steve_eth.xml, generated from the Wi-Fi profile: discovery to the
#          robot's wired port 192.168.60.90, UDP only on this PC's wired address + 127.0.0.1
#   no cable
#       -> Wi-Fi:    ~/.ros/fastdds_steve.xml (robot 10.7.4.213) + a WARNING: Wi-Fi gaps make the
#          WBC abort with "odom stale" / "/joint_states stale" (2026-10-15)
#
# STEVE_ROS_LINK=ethernet|wifi tells scripts which one is active. Force one: export STEVE_ROS_LINK_FORCE=wifi
# (or ethernet) before sourcing. After switching in an open terminal: ros2 daemon stop.

export ROS_DOMAIN_ID=69 RMW_IMPLEMENTATION=rmw_fastrtps_cpp
_steve_wifi_xml="$HOME/.ros/fastdds_steve.xml"
_steve_eth_xml="$HOME/.ros/fastdds_steve_eth.xml"
_steve_robot_eth=192.168.60.90
_steve_eth_ip=$(ip -4 -o addr show 2>/dev/null | awk '$4 ~ /^192\.168\.60\./ {split($4, a, "/"); print a[1]; exit}')

if [ "${STEVE_ROS_LINK_FORCE:-}" = "wifi" ] || { [ -z "$_steve_eth_ip" ] && [ "${STEVE_ROS_LINK_FORCE:-}" != "ethernet" ]; }; then
  export FASTRTPS_DEFAULT_PROFILES_FILE="$_steve_wifi_xml" STEVE_ROS_LINK=wifi
  case $- in *i*)
    printf '\033[1;33m[steve] WARNING: ROS over Wi-Fi (robot 10.7.4.213) — no Ethernet to the robot.\n'
    printf '        Gaps > --state_timeout stop the WBC ("odom stale"). Plug in the cable and open a new terminal.\033[0m\n' ;;
  esac
else
  # Ethernet profile = the Wi-Fi one with the robot's wired address and this PC's wired address whitelisted
  sed -e "s/10\.7\.4\.213/$_steve_robot_eth/g" \
      -e "1,6s|ROS 2 with Steve over Wi-Fi from this PC.*|ROS 2 with Steve over ETHERNET — GENERATED by ~/.ros/steve_dds.sh from fastdds_steve.xml, do not edit.|" \
      -e "/<maxMessageSize>1400<\/maxMessageSize>/a\\
      <interfaceWhiteList><address>${_steve_eth_ip:-192.168.60.155}</address><address>127.0.0.1</address></interfaceWhiteList>" \
      "$_steve_wifi_xml" > "$_steve_eth_xml.tmp" && mv "$_steve_eth_xml.tmp" "$_steve_eth_xml"
  export FASTRTPS_DEFAULT_PROFILES_FILE="$_steve_eth_xml" STEVE_ROS_LINK=ethernet
  case $- in *i*) printf '[steve] ROS over Ethernet: robot %s, this PC %s\n' "$_steve_robot_eth" "$_steve_eth_ip" ;; esac
fi
unset _steve_wifi_xml _steve_eth_xml _steve_robot_eth _steve_eth_ip
